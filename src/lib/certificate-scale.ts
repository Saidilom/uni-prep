import { MOCK_SCALE_MAX } from "./rasch";

// Итоговый балл сертификата.
//
// ШКАЛА ПРЕДМЕТНАЯ (решение владельца от 2026-09-10):
//
//   английский            — из 75
//   все остальные          — из 100
//
// У английского это не наш выбор, а норма: в src/lib/english-cefr.ts лежит
// таблица WRITING_RAW36_TO_SCORE75, переписанная дословно из Multilevel-bm.pdf,
// и она заканчивается ровно на 75.
//
// ═══ ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ПРЕЖНЕЙ СОТЕННОЙ ШКАЛЫ ═══
//
// С 2026-09-08 по 2026-09-10 шкала была одна, 75 на все предметы. Свели её
// туда потому, что до этого пороги уровней (70/65/60/55/50/46, заданы на
// T-шкале) сравнивались с сотенным баллом напрямую, и выходило нелепо:
//
//   63.0 из 100 → C          (T = 47.3)
//   60.3 из 100 → «Ниже C»   (T = 45.2)
//
// Шестьдесят баллов из ста означало «сертификата нет».
//
// Теперь сотенная шкала вернулась, но эта поломка — нет: пороги масштабируются
// вместе с баллом (levelFloorsFor в mock-grade-level.ts), поэтому на сотне C
// начинается с 61.3, и балл с порогом снова одно число. Букву это не сдвигает
// ни у кого: умножение балла и порогов на общий множитель монотонно.
//
// Не путать с блоками ПОСТУПЛЕНИЯ (93 и 63 балла, стр. 2 документа,
// «tabaqalashtirilgan ballar»): там своя арифметика Ball × 93/65, и она не про
// балл сертификата.

/**
 * Шкала ИЗМЕРЕНИЯ, а не максимум показанного балла.
 *
 * Раньше эта константа значила и то и другое, потому что шкала была одна.
 * Теперь максимум зависит от предмета (certificateMaxForSubject ниже), а здесь
 * остаётся общий эталон: на нём заданы пороги уровней и к нему приводятся
 * баллы разных предметов перед усреднением (scoreOnCertificateScale).
 *
 * Совпадает с MOCK_SCALE_MAX — выходом модели Раша, — и меняться не должен:
 * от него зависят raschThetaToT, погрешность (scoreSe = thetaSe · 10) и
 * официальная таблица английского.
 */
export const CERTIFICATE_MAX = MOCK_SCALE_MAX;

/** Максимум балла у английского — из государственной таблицы, не наш выбор. */
export const ENGLISH_CERTIFICATE_MAX = 75;

/** Максимум балла у остальных предметов. */
export const DEFAULT_CERTIFICATE_MAX = 100;

// ЕДИНСТВЕННОЕ место, где балл округляется.
//
// Раньше округление стояло трижды: в raschThetaToT (θ → T), в
// combineSectionScores (среднее разделов) и здесь. Каждое срезало точность
// независимо, и по методике Агентства балл выходил целым — 56, 68 — тогда как
// в сертификате у него есть десятая. Теперь первые два шага считают точно, а
// округление осталось одно, последнее.
//
// Два знака — решение владельца от 2026-09-11.
//
// Точность ПОКАЗА, а не измерения: в базе балл лежит неокруглённым
// (51.66561275680224), и второй знак ничего не пересчитывает — он лишь
// перестаёт скрывать то, что уже посчитано. Балл при этом точнее не становится:
// на реальном моке SE вышла ±3–5, и рядом с баллом стоит «±» именно поэтому.
//
// Точность в проекте одна на всё: cefr_score (/api/mock-tests/[id]/cefr-recalculate),
// средние по филиалу (get_branch_overview) и рейтинг класса
// (get_my_class_subject_ranking) округляются к тому же знаку — см. миграцию 115.
// Разойдутся — на экране встанут рядом «30,2» и «30,20», и второе пообещает
// точность, которой у первого нет.
export const SCORE_DECIMALS = 2;

// Множитель СЧИТАЕТСЯ из константы, а не зашит числом.
//
// Здесь стояло `Math.round(value * 10) / 10`, и при смене константы на два
// знака балл резался бы до одной десятой, а печатался с двумя: вместо 51,67
// вышло бы «51,70». Правка одной строки давала бы неверный результат в
// соседней — ровно та ловушка, что уже ловилась на шкале баллов.
const ROUND_FACTOR = 10 ** SCORE_DECIMALS;

export function roundScore(value: number): number {
  if (!Number.isFinite(value)) return 0;
  return Math.round(value * ROUND_FACTOR) / ROUND_FACTOR;
}

// Балл для показа. Печатать его сырым нельзя: 86.4 в double хранится неточно,
// и на экран вылезало бы «86.40000000000001».
//
// Запятая, а не точка. Так в ru/uz, и так же это важно для выгрузки: колонки в
// CSV разделены `;`, поэтому запятая внутри числа таблицу не ломает, зато Excel
// с русской локалью читает «67,8» как ЧИСЛО, а «67.8» — как текст, и среднее по
// колонке посчитать бы не вышло.
export function formatScore(score: number | null | undefined): string {
  if (score === null || score === undefined || !Number.isFinite(score)) return "";
  return score.toFixed(SCORE_DECIMALS).replace(".", ",");
}

// Балл с погрешностью: «31,42 ± 3,90».
//
// Нужен потому, что сотые доли балла обещают точность, которой нет. На
// реальном моке по математике SE вышла ±3,2–4,6 балла, и работы на 31,42 и
// 32,10 статистически неразличимы. Пока рядом не стоит ±, второй знак читается
// как «эти двое разные», а это неправда.
//
// Без погрешности возвращает просто балл, а не «± null»: у работ, посчитанных
// до миграции 093, SE в базе нет, и дописывать им выдуманную нельзя (§233).
export function formatScoreWithError(
  score: number | null | undefined,
  scoreSe: number | null | undefined,
): string {
  const base = formatScore(score);
  if (base === "") return "";
  if (scoreSe === null || scoreSe === undefined || !Number.isFinite(scoreSe) || scoreSe <= 0) return base;
  return `${base} ± ${formatScore(roundScore(scoreSe))}`;
}

// Интервал для показа: «20,25 – 35,64».
export function formatScoreInterval(interval: { low: number; high: number } | null): string {
  if (!interval) return "";
  return `${formatScore(interval.low)} – ${formatScore(interval.high)}`;
}

/**
 * Максимум балла по предмету.
 *
 * Ровно то место, ради которого предмет и оставляли в сигнатуре, когда шкала
 * была одна: правка вышла здесь одна, по вызовам ходить не пришлось.
 *
 * Предмет не указан — берём сотню: она у всех, кроме английского, и тест без
 * предмета почти наверняка общеобразовательный. Отдать ему 75 значило бы
 * занизить показанный балл на четверть.
 */
export function certificateMaxForSubject(subjectId: string | null | undefined): number {
  return subjectId === "english" ? ENGLISH_CERTIFICATE_MAX : DEFAULT_CERTIFICATE_MAX;
}

// Перевод T-балла в балл сертификата БЕЗ округления.
//
// §202–203 требуют разделить два разных действия: внутренний расчёт идёт в
// полной точности double, а округление стоит один раз и только на выводе.
// Отсюда две функции вместо одной.
//
// Эту берёт всё, что считает ДАЛЬШЕ: полоса уровня (§134 — интервал по точному
// значению), доверительный интервал, усреднение. Округлённую — только показ и
// запись показанного числа.
//
// Не выкинута, потому что это единственное место, через которое балл попадает
// в базу, и §R.3 вернёт сюда `A·θ + B` — тогда правка будет здесь.
/**
 * Тот же перевод, но шкала задаётся ЧИСЛОМ, а не предметом.
 *
 * Нужен там, где шкала закреплена за тестом (mock_tests.certificate_scale_max,
 * миграция 112) и может отличаться от предметной: у тестов до 2026-09-10 она
 * 75 даже по математике, потому что их результаты уже показаны ученикам и
 * пересчёту не подлежат.
 */
export function tScoreToScaleExact(tScore: number, max: number): number {
  if (!Number.isFinite(tScore) || !Number.isFinite(max) || max <= 0) return 0;
  const clamped = Math.max(0, Math.min(MOCK_SCALE_MAX, tScore));
  // Шкала совпадает — отдаём как есть, без кругового деления (см. ниже).
  if (max === MOCK_SCALE_MAX) return clamped;
  return (clamped / MOCK_SCALE_MAX) * max;
}

export function tScoreToCertificateExact(tScore: number, subjectId: string | null | undefined): number {
  const max = certificateMaxForSubject(subjectId);
  if (!Number.isFinite(tScore)) return 0;
  const clamped = Math.max(0, Math.min(MOCK_SCALE_MAX, tScore));
  // Шкала совпадает — отдаём как есть, без кругового деления.
  //
  // Это не оптимизация, а исправление живого бага. Раньше здесь безусловно
  // считалось (clamped / 75) × max, и при max = 75 выражение (55/75) × 75
  // давало 54.99999999999999: деление и умножение на одно и то же число
  // теряют последний бит двоичной дроби. Ученик с T ровно 55 получал C+
  // вместо B — то есть буква зависела от точности double, а не от нормы.
  //
  // Пороги считаются тем же порядком действий (levelFloorsFor), поэтому на
  // остальных шкалах балл и порог совпадают бит в бит.
  if (max === MOCK_SCALE_MAX) return clamped;
  return (clamped / MOCK_SCALE_MAX) * max;
}

// Тот же перевод, округлённый до сотых — для показа и для записи того
// числа, которое увидит ученик. Полосу уровня от него считать НЕЛЬЗЯ: округление
// может перенести балл через порог, которого точное значение не достигало.
export function tScoreToCertificate(tScore: number, subjectId: string | null | undefined): number {
  return roundScore(tScoreToCertificateExact(tScore, subjectId));
}

// Доля от максимума — ТОЛЬКО для цветовой заливки бейджа, где нужен процент.
// Для усреднения не годится: среднее процентов — процент, а не балл, и рядом
// с баллами из 75 читалось бы как завышенный балл. Усреднять — через
// `averageCertificateScore` ниже.
/**
 * Стоит ли вообще показывать погрешность числом.
 *
 * Есть случаи, когда «±» перестаёт быть информацией. Живой пример с прода:
 * ученик ответил на ОДНО задание из 55 и ошибся. По одному неверному ответу
 * способность не измеряется — θ вышла −5.4, информация 0.006, а погрешность
 * 13 логит, то есть ±130 баллов при шкале 75.
 *
 * Само число посчитано правильно, и статус LOW_INFORMATION выставлен верно.
 * Но «± 130,1» рядом с баллом читается как поломка, а доверительный интервал
 * при этом всё равно упирается в границы шкалы и покрывает её целиком —
 * то есть не сообщает ничего.
 *
 * Правило: если одна только полуширина интервала накрывает всю шкалу,
 * измерения нет, и вместо числа должен стоять статус (§215, §217). Широкая,
 * но осмысленная погрешность (±18 баллов — это интервал 0…36, он исключает
 * верхнюю половину шкалы) показывается как есть.
 */
export function errorIsShowable(
  scoreSe: number | null | undefined,
  z = 1.96,
  max: number = DEFAULT_CERTIFICATE_MAX,
): boolean {
  if (scoreSe === null || scoreSe === undefined || !Number.isFinite(scoreSe) || scoreSe <= 0) return false;
  // Сравнивать надо со шкалой ПОКАЗА: на сотне погрешность ±40 ещё что-то
  // сообщает (интервал 0…80 исключает верх), а на семидесяти пяти та же ±40
  // накрывает почти всё. Оставить здесь эталон 75 значило бы прятать
  // осмысленные погрешности у общеобразовательных предметов.
  return z * scoreSe < max;
}

export function certificatePercent(score: number | null, max: number | null): number | null {
  if (score === null || max === null || !Number.isFinite(score) || !Number.isFinite(max) || max <= 0) return null;
  return (score / max) * 100;
}

// Балл работы, приведённый к общей шкале измерения (75).
//
// Ради этого приведения шкал в базе и хранится level_score_max у каждой
// работы: у английского там 75, у остальных 100, а у работ до 2026-09-10 —
// 75 у всех. Складывать такие баллы напрямую нельзя, поэтому усреднение идёт
// через приведение, а не через сумму.
export function scoreOnCertificateScale(score: number | null, max: number | null): number | null {
  if (score === null || max === null || !Number.isFinite(score) || !Number.isFinite(max) || max <= 0) return null;
  return (score / max) * CERTIFICATE_MAX;
}

// Средний балл по нескольким работам — группы, учителя, филиала.
//
// Возвращает балл по общей шкале ИЗМЕРЕНИЯ (75), а не по шкале показа.
//
// Иначе среднее было бы несравнимым: в одной группе рядом лежат английский из
// 75 и математика из 100, а с 2026-09-10 ещё и работы двух эпох по одному
// предмету. Приведение к одной шкале — единственный способ получить число, у
// которого есть смысл.
//
// Отсюда следствие для интерфейса: подпись «средний балл» обязана называть
// шкалу, иначе рядом встанут «средний 30» и личный балл «76,5», и это
// прочтётся как ошибка.
//
// Работы без посчитанного балла в среднее не входят: их не с чем сравнивать,
// а ноль вместо них занизил бы результат группы.
//
// Результат НЕ округляется (§202–203): это тоже внутреннее значение, его
// показывает formatScore. Раньше здесь стоял roundScore, и среднее выходило
// округлением от округлённых баллов — две потери точности вместо нуля.
export function averageCertificateScore(
  results: Array<{ score: number | null; max: number | null }>,
): number | null {
  const normalized = results
    .map((r) => scoreOnCertificateScale(r.score, r.max))
    .filter((v): v is number => v !== null);
  if (normalized.length === 0) return null;
  return normalized.reduce((a, b) => a + b, 0) / normalized.length;
}
