import type { Locale } from "./i18n/config";

// Адреса языковых версий лендинга.
//
// ═══ ПОЧЕМУ У УЗБЕКСКОЙ ВЕРСИИ АДРЕС «/» ═══
//
// Язык в приложении переключается cookie на одном и том же URL. Для человека
// это удобно, а для поиска означает, что второй версии не существует вовсе:
// робот заходит без cookie, получает одну страницу и об остальных не узнаёт.
// Поэтому у лендинга два настоящих адреса.
//
// Узбекская версия живёт на корне, а не на `/uz`: именно ссылку
// `testregiston.uz` люди ищут и передают, и она же должна стоять в выдаче.
// Маршрут `/uz` при этом существует — на него middleware переписывает корень
// для неавторизованных, — но канонический адрес у него `/`, поэтому дубля в
// индексе не появляется.
export const LANDING_PATH: Record<Locale, string> = {
    uz: "/",
    ru: "/ru",
};

/** Полный адрес языковой версии — для canonical, hreflang и карты сайта. */
export function landingUrl(origin: string, locale: Locale): string {
    const path = LANDING_PATH[locale];
    return path === "/" ? `${origin}/` : `${origin}${path}`;
}
