// Баллы за вопросы теста — ровно те, что стоят в самом тесте: сумма ничему не
// подгоняется.
//
// Раньше здесь жила normalizePointsTo75, которая пропорционально растягивала
// баллы черновика так, чтобы их сумма была ровно 75, а getPublicationIssues
// не давала опубликовать тест с любой другой суммой. Это была ВТОРАЯ шкала «из
// 75» — рядом с настоящей, Rasch-овской (mock_results.level_score, миграция
// 034), и ученик видел на экране результата оба числа сразу. Настоящую оставили,
// самодельную убрали; см. design/FIX.md, раздел «Две шкалы 75».
//
// Сумма баллов теперь свободная, а сопоставимость между тестами с разным
// максимумом обеспечивает не она, а модель Раша: она же учитывает и сложность
// каждого вопроса, ради которой затевалось перевзвешивание в finalize.
function round2(value: number): number {
  return Math.round(value * 100) / 100;
}

export function sumPoints(points: number[]): number {
  return round2(points.reduce((sum, value) => sum + value, 0));
}
