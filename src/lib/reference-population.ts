// Эталонная популяция для Z-стандартизации — «относительно кого» считается балл.
//
// Методика Агентства (Baholash_mezoni.pdf, стр. 1–2) предписывает ровно это:
//
//   Z = (θ − μ) / σ,   T = 50 + 10·Z
//
// Формула у нас была верная, а μ и σ — нет. Мы брали их из когорты ТОГО ЖЕ
// теста, то есть измеряли людей относительно самих себя. Последствия были
// измерены на проде: средний T всегда выходил ровно 50, а средний балл — всегда
// 66.67 из 100. По математике когорта решила 23.3% заданий и оказалась заметно
// ниже своего пула (θ = −1.836), но получила те же 66.67, и когорта, решившая
// 5%, получила бы столько же. Прогресс между месяцами при этом измерить нельзя
// — ровно то, ради чего модель Раша и берётся.
//
// БМБА стандартизует по национальной популяции экзамена: большой и, главное,
// НЕИЗМЕННОЙ. Поэтому μ и σ здесь — зафиксированные числа, а не свойство
// сдавших. Отсюда следует всё остальное:
//
//   — балл становится функцией одной θ (RASCH.md §136–137: score ≠ θ, но
//     преобразование фиксировано и версионировано);
//   — сильная когорта больше не понижает балл каждому;
//   — прогресс за месяц становится настоящей величиной;
//   — исчезает молчаливая подмена разброса при вырожденной когорте, которая
//     нарушала §233 (NO SILENT FALLBACK): подменять больше нечего.
//
// ЧЕГО ЭТО НЕ ДАЁТ. Абсолютная привязка к шкале БМБА так не появляется:
// перевод θ → балл сертификата не публикуется и выводится только эмпирическим
// линкингом с реальными сертификатами (RASCH.md §268). До него любые μ и σ —
// осознанный placeholder, и после линкинга он заменяется одним преобразованием
// A·θ + B.

export type ReferencePopulation = {
    /** Версия набора. Меняется при любой правке μ или σ — старые баллы иначе невоспроизводимы. */
    version: string;
    /** Средняя способность эталонной популяции, логиты. */
    mu: number;
    /** Разброс способностей эталонной популяции, логиты. */
    sigma: number;
};

// v1 заморожена по фактическим сдачам 2026-09-06 — это всё, что было. Значения
// взяты с полной точностью из прода: avg(rasch_score) и stddev_pop(rasch_score)
// по предмету. Именно поэтому переход НИЧЕГО не сломал: на этих же данных
// заморозка воспроизводит уже показанные баллы один в один (проверено, 90 из
// 90), и переписывать историю не понадобилось (§239).
//
// Слабое место эталона названо честно: 36 и 54 человека, решившие 23% и 35%.
// Популяция тонкая и слабая, поэтому будущая сильная когорта получит высокие
// баллы. Это лечится не подкруткой чисел, а линкингом §268 — до него менять μ
// и σ вручную нельзя: балл потеряет сопоставимость с уже выданными.
const REFERENCE_V1: Record<string, ReferencePopulation> = {
    math: { version: "v1-2026-09", mu: -1.83649658661740109, sigma: 1.0547926831097154 },
    uzbek: { version: "v1-2026-09", mu: -1.089517161794192188, sigma: 1.1843407928254671 },
};

// Предмет, по которому эталона ещё нет. μ = 0 значит «T = 50 у того, чья
// способность вровень со средним заданием теста»: estimateRasch центрирует
// сложности через recenter(), поэтому θ = 0 — осмысленная точка, а не
// произвольная. σ = 1 — типичный разброс живой группы; у наших двух предметов
// он и вышел 1.05 и 1.18, так что единица не выдумана, а близка к измеренному.
//
// Это НЕ fallback в смысле §233: значение задано конфигурацией, помечено своей
// версией и одинаково для всех, а не подставляется молча в зависимости от
// данных.
export const REFERENCE_DEFAULT: ReferencePopulation = { version: "default-v1", mu: 0, sigma: 1 };

export function referencePopulationFor(subjectId: string | null | undefined): ReferencePopulation {
    if (!subjectId) return REFERENCE_DEFAULT;
    return REFERENCE_V1[subjectId] ?? REFERENCE_DEFAULT;
}

/** Есть ли у предмета замороженный эталон — для отчётов о качестве измерения. */
export function hasFrozenReference(subjectId: string | null | undefined): boolean {
    return Boolean(subjectId && subjectId in REFERENCE_V1);
}
