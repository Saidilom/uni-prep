// Эталонная популяция для Z-стандартизации — «относительно кого» считается балл.
//
// Методика Агентства (Baholash_mezoni.pdf, стр. 1–2) предписывает ровно это:
//
//   Z = (θ − μ) / σ,   T = 50 + 10·Z
//
// Формула у нас была верная, а μ и σ — нет. Мы брали их из когорты ТОГО ЖЕ
// теста, то есть измеряли людей относительно самих себя. Последствия были
// измерены на проде: средний T всегда выходил ровно 50, а средний балл — всегда
// 66.67 из 100. По математике когорта решила 23.3% заданий и оказалась заметно
// ниже своего пула (θ = −1.836), но получила те же 66.67, и когорта, решившая
// 5%, получила бы столько же. Прогресс между месяцами при этом измерить нельзя
// — ровно то, ради чего модель Раша и берётся.
//
// БМБА стандартизует по национальной популяции экзамена: большой и, главное,
// НЕИЗМЕННОЙ. Поэтому μ и σ здесь — зафиксированные числа, а не свойство
// сдавших. Отсюда следует всё остальное:
//
//   — балл становится функцией одной θ (RASCH.md §136–137: score ≠ θ, но
//     преобразование фиксировано и версионировано);
//   — сильная когорта больше не понижает балл каждому;
//   — прогресс за месяц становится настоящей величиной;
//   — исчезает молчаливая подмена разброса при вырожденной когорте, которая
//     нарушала §233 (NO SILENT FALLBACK): подменять больше нечего.
//
// ЧЕГО ЭТО НЕ ДАЁТ. Абсолютная привязка к шкале БМБА так не появляется:
// перевод θ → балл сертификата не публикуется и выводится только эмпирическим
// линкингом с реальными сертификатами (RASCH.md §268). До него любые μ и σ —
// осознанный placeholder, и после линкинга он заменяется одним преобразованием
// A·θ + B.

export type ReferencePopulation = {
    /** Версия набора. Меняется при любой правке μ или σ — старые баллы иначе невоспроизводимы. */
    version: string;
    /** Средняя способность эталонной популяции, логиты. */
    mu: number;
    /** Разброс способностей эталонной популяции, логиты. */
    sigma: number;
};

// НУЛЕВОЙ ЭТАЛОН — единая точка отсчёта для всех предметов.
//
//   50 баллов по T-шкале = способность вровень со СРЕДНИМ ЗАДАНИЕМ теста.
//
// Ноль здесь не произвольный: estimateRasch центрирует сложности через
// recenter(), поэтому θ = 0 — это ровно «вровень со средним заданием», а не
// случайная величина. σ = 1 — одна логита на 10 баллов T; у наших двух
// предметов измеренный разброс вышел 1.05 и 1.18, так что единица близка к
// наблюдаемому, а не выдумана.
//
// ПОЧЕМУ НЕ ЗАМОРОЖЕННАЯ ПОПУЛЯЦИЯ. Сначала эталоном были сделаны фактические
// сдачи 2026-09-06: так уже показанные баллы совпадали один в один, и историю
// не приходилось трогать. Но эталоном при этом становились те, кто решил 23% и
// 35% заданий, и абсолютный уровень оставался завышенным — за половину
// решённого теста выходило 90 баллов, за 28% решённого — 61.
//
// Владелец выбрал правдоподобие абсолютного уровня, а не сопоставимость с
// сентябрьскими баллами. Ценой стала правка задним числом: миграция 091
// пересчитала все 90 работ и создала ревизии (§239). Числа после перехода:
//
//   верных 15% → 19 баллов    (было 44.4)
//   верных 28% → 36.6         (было 61.4)
//   верных 53% → 69.9         (было 90.4)
//   верных 78% → 95.4         (было 100)
//
// ЧТО ЭТО ВСЁ ЕЩЁ НЕ ДАЁТ. Настоящей привязки к шкале БМБА нет: перевод
// θ → балл сертификата не публикуется и выводится только эмпирическим
// линкингом с реальными сертификатами (design/RASCH.md §268). Нулевой эталон —
// осознанный placeholder, и после линкинга он заменяется одним преобразованием
// A·θ + B. До линкинга менять μ и σ вручную нельзя: любая правка сдвинет все
// баллы разом и потребует новой ревизии.
export const REFERENCE_DEFAULT: ReferencePopulation = { version: "v2-zero", mu: 0, sigma: 1 };

// Предметной таблицы сейчас нет намеренно: один эталон на все предметы. Разные
// μ по предметам означали бы разные точки отсчёта, а сравнивать баллы по
// математике и английскому и без того нельзя (§118–120) — расхождение точек
// отсчёта сделало бы это ещё и незаметным.
//
// Предмет тем не менее остаётся в сигнатуре, и это не забытый аргумент:
// линкинг с БМБА (§268) собирает по 100–150 учеников НА ПРЕДМЕТ, то есть
// эталон почти наверняка станет попредметным. Вызывающие уже передают предмет,
// поэтому переход не заденет ни одного места вызова, а сейчас параметр
// документирует, что точка отсчёта — свойство предмета, а не платформы.
// eslint-disable-next-line @typescript-eslint/no-unused-vars
export function referencePopulationFor(subjectId: string | null | undefined): ReferencePopulation {
    return REFERENCE_DEFAULT;
}
