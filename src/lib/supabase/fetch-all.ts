// PostgREST режет любой ответ по настройке проекта `max_rows` — молча, без
// ошибки: массив просто приходит короче, чем строк в базе. Любой код, который
// считает агрегат по «всем» строкам, при этом становится тихо неверным.
//
// Это уже стреляло: /api/rasch/recalculate вытаскивал все строки ответов теста
// и считал по ним модель Раша. На группе из 100 учеников по 35 вопросов (3500
// строк) до него доходило 1000, а список учеников строился по полному набору
// результатов — поэтому ~72 ученика давали НОЛЬ наблюдений и всё равно
// получали записанную оценку и уровень, который виден им на экране.
// Замечено на живом проде: запрос вернул ровно 1000 строк из 3500, причём и
// под service_role — эта роль ограничитель не обходит.
//
// Порог зависит только от числа строк, поэтому ломается уже на обычном классе:
// при тесте на 71 вопрос усечение начинается с 15-го ученика.
//
// Настройка проекта поднята до 20000, но полагаться на неё нельзя: значение
// живёт вне репозитория, его может изменить кто угодно, а группы растут.
// Этот хелпер делает результат независимым от неё.
//
// Дженерики `supabase.from<T>()` в этой версии клиента сломаны (см. CLAUDE.md),
// поэтому хелпер принимает колбэк и типизируется только по возвращаемому
// значению — никаких типов из postgrest-js он не импортирует.
const PAGE_SIZE = 1000;

type PageResult<T> = { data: T[] | null; error: { message: string } | null };

/**
 * Читает все строки запроса постранично, а не первую страницу.
 *
 * `loadPage` должен применить `.range(from, to)` к вашему запросу и вернуть
 * его результат. Хелпер повторяет вызов, пока страницы приходят полными.
 *
 * Ошибку возвращает явно: получить короткий массив и не узнать об этом —
 * ровно та беда, от которой это и написано.
 *
 * ВАЖНО: у запроса должен быть детерминированный порядок, иначе строки между
 * страницами могут повторяться или пропадать. Если `.order()` не задан,
 * добавьте его на вызывающей стороне.
 */
export async function fetchAllRows<T>(
  loadPage: (from: number, to: number) => PromiseLike<PageResult<T>>
): Promise<{ data: T[]; error: { message: string } | null }> {
  const all: T[] = [];
  let from = 0;

  for (;;) {
    const { data, error } = await loadPage(from, from + PAGE_SIZE - 1);
    if (error) return { data: all, error };
    const page = data ?? [];
    all.push(...page);
    // Неполная страница означает, что строки закончились.
    if (page.length < PAGE_SIZE) return { data: all, error: null };
    from += PAGE_SIZE;
  }
}
