-- 104. Учитель читает калибровку заданий. Нужно графикам §D.3, D.10–D.12.
--
-- ═══ ЗАЧЕМ ═══
--
-- TIF, TCC, ICC и карта Райта строятся из сложностей заданий b. До сих пор у
-- mock_item_calibration была ровно одна политика — is_admin(), — поэтому у
-- учителя на том же экране отчёта графики оказались бы пустыми.
--
-- ═══ ПОЧЕМУ ЭТО НЕ РАСШИРЯЕТ ДОСТУП К СОДЕРЖАНИЮ ═══
--
-- Учитель УЖЕ читает mock_answer_details по всему моку (политика
-- mock_answer_details для назначенных классов) и строит из неё долю ошибок по
-- каждому заданию — это и есть исходник, из которого выводится сложность.
-- Раш-мера b является монотонным преобразованием той же доли, только
-- отцентрованным и в логитах. Ничего нового о заданиях она не сообщает.
--
-- Ключа здесь нет вовсе: в таблице лежат b, SE(b), fit и размер выборки, но не
-- правильные ответы. Этим она отличается от mock_distractor_stats (миграция
-- 103), которую учителю тоже видно, а ученику намеренно нет.
--
-- Ученику НЕ открывается: знание, какие задания трудные, до сдачи теста —
-- преимущество, которого у него быть не должно.

DROP POLICY IF EXISTS mock_item_calibration_teacher_read ON public.mock_item_calibration;
CREATE POLICY mock_item_calibration_teacher_read ON public.mock_item_calibration
  FOR SELECT USING (public.is_teacher());

COMMENT ON POLICY mock_item_calibration_teacher_read ON public.mock_item_calibration IS
  'Учителю нужны сложности для психометрических графиков (§D.3, D.10-D.12). Доля ошибок по заданиям ему уже доступна через mock_answer_details, поэтому новой информации b не несёт.';

NOTIFY pgrst, 'reload schema';
