-- 117. Балл считает 3PL. Прежняя модель убрана.
--
-- ═══ РЕШЕНИЕ ВЛАДЕЛЬЦА ОТ 2026-09-13 ═══
--
-- «Нужно чтобы всё работало по новой 3PL, а бывшую убрать вообще и обновить
-- данные под новую». Принято после того, как сравнение обеих моделей было
-- показано на его же работах (миграция 116):
--
--   математика 36 работ: буква разошлась у 21, средний разрыв 14,10,
--                        максимальный 49,18, корреляция θ 0,671
--   Ona Tili   54 работы: буква разошлась у 37, средний разрыв 23,79,
--                        корреляция θ 0,818
--
-- ═══ ЧТО ЭТО МЕНЯЕТ В ДАННЫХ ═══
--
-- 1. У задания теперь ТРИ параметра. difficulty остаётся (это b), рядом
--    появляются discrimination (a) и guessing (c).
--
-- 2. Таблица mock_score_lookup теряет смысл. Она существовала потому, что в
--    модели Раша сырой балл однозначно задавал θ: у всех с одинаковым числом
--    верных был один и тот же балл. В 3PL задания входят со своими весами
--    a_i, и у двух учеников с одинаковым числом верных θ РАЗНАЯ — таблицей из
--    56 строк такой расчёт описать нельзя. Строки удаляются, сама таблица
--    остаётся пустой: удалять её отдельной миграцией, пока на неё ссылается
--    старый код, рискованнее, чем оставить.
--
-- 3. Отдельные таблицы сравнения (миграция 116) больше не нужны: сравнивать
--    не с чем, прежней модели нет.
--
-- 4. Заморозка статистики потока СНИМАЕТСЯ. θ теперь в другой метрике, и
--    старые μ и σ к ней не относятся — с ними баллы считались бы от чужой
--    точки отсчёта.

ALTER TABLE public.mock_item_calibration
  ADD COLUMN IF NOT EXISTS discrimination numeric,
  ADD COLUMN IF NOT EXISTS guessing numeric,
  ADD COLUMN IF NOT EXISTS guessing_prior numeric,
  ADD COLUMN IF NOT EXISTS option_count int;

COMMENT ON COLUMN public.mock_item_calibration.difficulty IS
  'Параметр b модели 3PL — уровень θ, при котором P = (1+c)/2. До 2026-09-13 это была трудность модели Раша.';
COMMENT ON COLUMN public.mock_item_calibration.discrimination IS
  'Параметр a: крутизна кривой. NULL у строк, посчитанных до перехода на 3PL.';
COMMENT ON COLUMN public.mock_item_calibration.guessing IS
  'Параметр c: нижняя асимптота, вероятность угадать. 0 у заданий со свободным ответом.';
COMMENT ON COLUMN public.mock_item_calibration.guessing_prior IS
  'Центр априорного распределения c, равен 1/k. По нему видно, держит оценку c данными или априором — при малой выборке это разные вещи.';

-- Таблица «сырой балл → θ» под 3PL неверна: чистим и оставляем пустой.
DELETE FROM public.mock_score_lookup;

COMMENT ON TABLE public.mock_score_lookup IS
  'НЕ ЗАПОЛНЯЕТСЯ с 2026-09-13. Имела смысл только при модели Раша, где сырой балл однозначно задавал θ. В 3PL у двух учеников с одинаковым числом верных балл разный — расчёт объясняет панель «Модель 3PL», а не таблица.';

-- Сравнивать больше не с чем: прежней модели нет.
DROP TABLE IF EXISTS public.mock_result_3pl;
DROP TABLE IF EXISTS public.mock_item_calibration_3pl;

-- Заморозка снимается: пересчёт обязан задать точку отсчёта заново, уже в
-- метрике 3PL.
UPDATE public.mock_tests
   SET cohort_frozen_at = NULL, cohort_mu = NULL, cohort_sigma = NULL, cohort_n = NULL
 WHERE cohort_frozen_at IS NOT NULL;

NOTIFY pgrst, 'reload schema';
