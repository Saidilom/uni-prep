-- Снятие замороженной точки отсчёта после починки оценки θ.
--
-- ═══ ЗАЧЕМ ═══
--
-- До этой правки θ оценивалась голым максимумом правдоподобия, у которого в
-- 3PL ниже уровня угадывания максимума НЕТ: оценка упиралась в границу шкалы
-- −8. На боевой математике так лежали 9 работ из 36, на Ona Tili — 7 из 54.
--
-- Эти границы попадали в статистику потока, и заморожена оказалась испорченная
-- точка отсчёта:
--
--   математика: mu = −2,388  sigma = 3,395   (настоящие −0,588 и 0,817)
--   Ona Tili:   mu = −1,151  sigma = 2,793   (настоящие −0,292 и 0,905)
--
-- Балл считается как T = 50 + 10(θ−mu)/sigma, поэтому раздутая sigma сжимала
-- балл ВСЕМ остальным: лучшая работа математики получала 62,33 вместо 75,00.
--
-- Пересчёт берёт замороженную статистику в приоритет — и это правильно, пока
-- она получена той же моделью, что и θ. Здесь она получена другой, поэтому
-- заморозка снимается, и пересчёт задаёт точку отсчёта заново. Та же причина и
-- тот же шаг, что в миграции 117 при переходе на 3PL.
--
-- ═══ ЧТО ЭТО ЗНАЧИТ ДЛЯ УЖЕ ПОКАЗАННЫХ БАЛЛОВ ═══
--
-- Они изменятся, и это осознанно (§239): прежние значения лягут в
-- mock_result_revisions с reason = 'theta_map_fix' и scale_version =
-- '3pl-1.0/mle-newton' — их пишет сам пересчёт до перезаписи. Оставить
-- показанные баллы как есть нельзя: они получены оценкой, которая девяти
-- работам с разным числом верных давала один и тот же балл.

